"""Intake (T-DEV-048): turn a finished worker's branch into a pull request that is ready for independent review.

    python -B -m dev_supervisor.intake <worker-id> [--yes] [--base main]

After a worker exits, Main did the same steps by hand every time. This module does exactly those steps from the worker
record, as a dry run unless ``--yes``:

1. the worker is known, no longer active, and is on its registered ``task/`` branch in its own worktree;
2. the worktree is clean (nothing uncommitted) and the branch has at least one commit of its own;
3. the task is registered on ``origin/<base>`` for that branch;
4. the merge preflight (``integrate.preflight``: branch name, handoff, scope, secrets, forbidden files, reserved paths)
   passes on the committed branch;
5. with ``--yes``: ``origin/<base>`` is merged into the branch when it is behind (a conflict aborts the merge and
   refuses), the preflight is repeated, the registered branch is pushed (never forced) and the pull request is opened
   with a body built from recorded facts only.

It never merges a pull request, never reviews, never edits files and never force-pushes. A worker that did not
finish is disclosed as such in the body. The body is scanned for credential shapes and refused if any is found. The
printed diff hash is the hash an independent review must bind to (``integrate`` computes the same value).
"""
from __future__ import annotations

import argparse
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Sequence, TextIO, Tuple

from . import integrate
from .workers import Worker, WorkerStatus

__all__ = ["Result", "intake", "build_body", "main"]

Git = Callable[[Sequence[str]], Tuple[int, bytes]]
Gh = Callable[..., Tuple[int, str]]

TERMINAL = (WorkerStatus.EXITED, WorkerStatus.FAILED, WorkerStatus.STOPPED, WorkerStatus.BLOCKED, WorkerStatus.LOST)
TITLE_MAX = 110


@dataclass
class Result:
    problems: List[str] = field(default_factory=list)
    lines: List[str] = field(default_factory=list)       # what was or would be done
    gates: List[integrate.Gate] = field(default_factory=list)
    diff_sha: str = ""
    pr_url: str = ""

    @property
    def ok(self) -> bool:
        return not self.problems


def _txt(out: Any) -> str:
    return (out.decode("utf-8", "replace") if isinstance(out, bytes) else str(out)).strip()


def _duration(w: Worker) -> str:
    from .state_store import parse_iso
    a, b = parse_iso(w.started_at), parse_iso(w.ended_at)
    if a is None or b is None or b < a:
        return "unknown"
    secs = int(b - a)
    return f"{secs // 60} min {secs % 60} s"


def build_body(w: Worker, title: str, commits: Sequence[str], files: Sequence[str], diff_sha: str) -> str:
    """Pull request body from recorded facts only. No file contents, no prompt, no environment."""
    alloc = w.allocation if isinstance(w.allocation, dict) else {}
    finished = w.status == WorkerStatus.EXITED and w.exit_code in (0, None)
    state = (f"{w.status}" + (f", exit code {w.exit_code}" if w.exit_code is not None else "")
             + (f", restarted {w.restart_count} time(s)" if w.restart_count else ""))
    lines = [
        f"Task {w.task_id}: {title}",
        "",
        "**Provenance (recorded by the supervisor).** This branch was produced by a dispatched worker, not by Main.",
        f"- worker: {w.worker_id}; role: {w.role}; route: {w.provider}/{w.model}" if not str(w.model).startswith(str(w.provider) + "/")
        else f"- worker: {w.worker_id}; role: {w.role}; route: {w.model}",
        f"- allocation role: {alloc.get('role', 'not recorded')}; capability {alloc.get('capability', 'not recorded')}",
        f"- run: {_duration(w)}; end state: {state}",
        ("- the worker finished and exited normally; this is still an unreviewed claim until an independent review binds to the diff hash"
         if finished else
         "- **the worker did NOT finish cleanly** (see end state). The commits below may be incomplete; Main checked them before opening this pull request"),
        "- Main did not edit the worker's commits. Main only merged the base branch into the branch if it was behind, pushed it (workers may not push) and opened this pull request.",
        "",
        f"**Commits ({len(commits)})**",
        *[f"- {c}" for c in commits[:20]],
        "",
        f"**Files changed ({len(files)})**",
        *[f"- {f}" for f in files[:40]],
        "",
        f"**Review.** UNREVIEWED. An independent review must bind to diff hash `{diff_sha or 'unknown'}` "
        "(`python -B -m dev_supervisor.integrate --preflight` prints it).",
        "",
        "Generated by `python -B -m dev_supervisor.intake`.",
    ]
    return "\n".join(lines) + "\n"


def _task_title(git: Git, base: str, w: Worker) -> Tuple[Optional[str], str]:
    import json
    rc, out = git(["show", f"origin/{base}:ACTIVE_TASKS.json"])
    if rc != 0:
        return None, f"ACTIVE_TASKS.json is not readable on origin/{base}"
    try:
        doc = json.loads(out.decode("utf-8", "replace"))
        tasks = [t for t in doc.get("tasks", []) if isinstance(t, dict)]
    except (ValueError, AttributeError):
        return None, f"ACTIVE_TASKS.json on origin/{base} is not valid"
    for t in tasks:
        if t.get("id") == w.task_id:
            if t.get("branch") != w.branch:
                return None, f"task {w.task_id} is registered on branch {t.get('branch')!r}, not on the worker's {w.branch!r}"
            return str(t.get("title") or w.task_id), ""
    return None, f"task {w.task_id} is not registered on origin/{base}"


def intake(w: Worker, git: Git, gh: Gh, *, yes: bool = False, base: str = "main", worktree_exists: Optional[bool] = None) -> Result:
    """Check a finished worker's branch and, with ``yes``, publish it. ``git`` runs in the worker's worktree."""
    r = Result()

    def refuse(msg: str) -> Result:
        r.problems.append(integrate._clean(msg, 300))
        return r

    if w.status not in TERMINAL:
        return refuse(f"worker {w.worker_id} is {w.status}: intake needs a worker that has ended")
    if not str(w.branch).startswith("task/"):
        return refuse(f"the worker's branch {w.branch!r} does not start with task/")
    exists = os.path.isdir(w.worktree) if worktree_exists is None else worktree_exists
    if not exists:
        return refuse("the worker's worktree directory does not exist")
    rc, out = git(["rev-parse", "--abbrev-ref", "HEAD"])
    if rc != 0 or _txt(out) != w.branch:
        return refuse(f"the worktree is on {(_txt(out) or 'an unreadable ref')!r}, not on the registered branch {w.branch!r}")
    rc, out = git(["status", "--porcelain"])
    if rc != 0:
        return refuse("git status failed in the worktree")
    if _txt(out):
        return refuse("the worktree has uncommitted changes; review and commit them by hand or discard them, intake only publishes commits")

    title, why = _task_title(git, base, w)
    if title is None:
        return refuse(why)

    gates, info = integrate.preflight(git, base)
    r.gates, r.diff_sha = gates, info.get("diff_sha", "")
    failing = [f"{g.name}: {g.status}" for g in gates if g.status != integrate.PASS]
    if failing:
        return refuse("the merge preflight does not pass (" + "; ".join(failing) + ")")

    rc, out = git(["rev-list", "--count", "--no-merges", f"origin/{base}..HEAD"])
    if rc != 0 or not _txt(out).isdigit() or int(_txt(out)) < 1:
        return refuse("the branch has no commit of its own beyond the base: there is nothing to publish")
    rc, out = git(["log", "--no-merges", "--format=%h %s", f"origin/{base}..HEAD"])
    commits = [integrate._clean(x, 160) for x in _txt(out).splitlines() if x.strip()] if rc == 0 else []
    rc, out = git(["diff", "--name-only", "--no-renames", f"origin/{base}...HEAD"])
    files = [x for x in _txt(out).splitlines() if x.strip()] if rc == 0 else []

    behind = git(["merge-base", "--is-ancestor", f"origin/{base}", "HEAD"])[0] != 0
    r.lines.append(f"worker {w.worker_id} ({w.status}) on {w.branch}: {len(commits)} commit(s), {len(files)} file(s), diff {r.diff_sha or 'unknown'}")
    r.lines.append(f"origin/{base} is " + ("ahead of the branch: it would be merged in first" if behind else "already contained in the branch"))
    r.lines.append("then: push " + w.branch + " (no force) and open the pull request")
    if not yes:
        return r

    if behind:
        rc, _ = git(["merge", "--no-edit", f"origin/{base}"])
        if rc != 0:
            git(["merge", "--abort"])
            return refuse(f"merging origin/{base} into the branch conflicts; the merge was aborted, resolve it by hand")
        gates, info = integrate.preflight(git, base)
        r.gates, r.diff_sha = gates, info.get("diff_sha", "")
        failing = [f"{g.name}: {g.status}" for g in gates if g.status != integrate.PASS]
        if failing:
            return refuse("after merging the base the preflight does not pass (" + "; ".join(failing) + ")")
    body = build_body(w, title, commits, files, r.diff_sha)
    if integrate._secret_hits(body.splitlines()):
        return refuse("the pull request body would contain a credential-shaped string; nothing was pushed")
    rc, out = gh(["pr", "list", "--head", w.branch, "--state", "open", "--json", "number", "--jq", "length"])
    if rc == 0 and _txt(out) not in ("", "0"):
        return refuse(f"a pull request is already open for {w.branch}")
    rc, _ = git(["push", "-u", "origin", w.branch])
    if rc != 0:
        return refuse("git push was rejected or failed (never forced); check the remote branch")
    pr_title = integrate._clean(f"{w.task_id}: {title}", TITLE_MAX)
    rc, out = gh(["pr", "create", "--base", base, "--head", w.branch, "--title", pr_title, "--body-file", "-"], input=body)
    if rc != 0:
        return refuse("the branch was pushed but the pull request could not be opened: " + integrate._clean(out, 200))
    r.pr_url = _txt(out).splitlines()[-1] if _txt(out) else ""
    r.lines.append("opened " + (r.pr_url or "the pull request"))
    return r


def main(argv: Optional[Sequence[str]] = None, out: Optional[TextIO] = None, *, registry: Any = None,
         git_factory: Optional[Callable[[Path], Git]] = None, gh: Optional[Gh] = None) -> int:
    out = out or sys.stdout
    ap = argparse.ArgumentParser(prog="dev_supervisor.intake", description="Publish a finished worker's branch as a pull request (dry run unless --yes).")
    ap.add_argument("worker_id")
    ap.add_argument("--yes", action="store_true", help="merge the base in if behind, push the branch and open the pull request")
    ap.add_argument("--base", default="main")
    a = ap.parse_args(argv)
    try:
        if registry is None:
            from . import config as config_mod
            from .state_store import StateStore
            from .workers import WorkerRegistry
            cfg = config_mod.load()
            registry = WorkerRegistry(StateStore(cfg.state_directory(), repo_roots=[], create=False))
        w = registry.get(a.worker_id)
    except Exception as e:                       # unknown worker, unreadable state
        print(f"refused: cannot read worker {a.worker_id}: {type(e).__name__}", file=out)
        return 2
    git = (git_factory or integrate.real_git_runner)(Path(w.worktree))
    res = intake(w, git, gh or integrate.real_gh_runner(Path(w.worktree)), yes=a.yes, base=a.base)
    if res.gates:
        print(integrate.render_table(res.gates), file=out)
    for line in res.lines:
        print(("" if a.yes else "[dry run] ") + line, file=out)
    if not res.ok:
        print("refused:", file=out)
        for p in res.problems:
            print("  - " + p, file=out)
        return 1
    if not a.yes:
        print("dry run: nothing changed. Review bound to diff " + (res.diff_sha or "unknown") + "; rerun with --yes to publish.", file=out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
